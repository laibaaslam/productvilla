// product list bases on page no
export const productListController = async (req, res) => {
    try {
        // ininitally 6 pages
        const perPage = 4;
        // req param for pgae else 1 
        const page = req.params.page ? req.params.page : 1;
        const products = await productModel
            .find({})
            .select("-photo")
            // how many images to skip
            .skip((page - 1) * perPage)
            // no of toatal obj
            .limit(perPage)
            .sort({ createdAt: -1 });
        res.status(200).send({
            success: true,
            products,
        });
    } catch (error) {
        console.log(error);
        res.status(400).send({
            success: false,
            message: "error in per page ctrl",
            error,
        });
    }
};

